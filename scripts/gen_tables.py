#!/usr/bin/env python3
"""Regenerate src/tables.rs from Python's unicodedata: `python3 scripts/gen_tables.py > src/tables.rs`.

Replaces hand-maintained Unicode tables. Python's Unicode version decides the data; CI does not run this.
The HTML entity table is gone: html5ever ships its own (`html5ever::data::NAMED_ENTITIES`).
"""
import sys
import unicodedata as ud

WIDTH = 114  # body of a row before the 4-space indent


def esc(s):
    return "".join(c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else "\\u{%x}" % ord(c) for c in s)


def rows(items):
    out, line = [], ""
    for it in items:
        if line and len(line) + 1 + len(it) > WIDTH:
            out.append("    " + line)
            line = it
        else:
            line = f"{line} {it}" if line else it
    if line:
        out.append("    " + line)
    return "\n".join(out)


def fold1(c):
    """The prototype's fold() on one char: NFKD minus combining marks (lowercasing stays at run time)."""
    return "".join(x for x in ud.normalize("NFKD", c) if not ud.combining(x))


def main():
    fold, comb, zeros = [], [], []
    for u in range(0x80, 0x110000):
        c = chr(u)
        if 0xAC00 <= u <= 0xD7A3:
            continue  # Hangul syllables: decomposed by formula in clean::fold
        if ud.combining(c):
            if comb and comb[-1][1] == u - 1:
                comb[-1][1] = u
            else:
                comb.append([u, u])
            continue
        f = fold1(c)
        if f != c:
            fold.append(f'(0x{u:x}, "{esc(f)}"),')
    for u in range(0x110000):
        if ud.category(chr(u)) == "Nd" and ud.digit(chr(u), -1) == 0:
            zeros.append(f"0x{u:x},")
    p = sys.stdout.write
    p("//! Generated by scripts/gen_tables.py (Python %s, Unicode %s). Regenerate, never hand-edit.\n"
      % (sys.version.split()[0], ud.unidata_version))
    p("//! Replaces the `unicodedata` calls of the oracle's `fold()` (FOLD = NFKD minus combining marks for every\n"
      "//! non-combining code point except Hangul syllables, which decompose by formula; COMBINING = every ccc > 0\n"
      "//! range) and regex `\\d` (ND_ZEROS = first code point of every Unicode Nd run of ten).\n\n")
    p("#[rustfmt::skip]\npub static FOLD: &[(u32, &str)] = &[\n" + rows(fold) + "\n];\n\n")
    p("#[rustfmt::skip]\npub static COMBINING: &[(u32, u32)] = &[\n"
      + rows(f"(0x{a:x}, 0x{b:x})," for a, b in comb) + "\n];\n\n")
    p("#[rustfmt::skip]\npub static ND_ZEROS: &[u32] = &[\n" + rows(zeros) + "\n];\n")


main()
